    public Sessions(Sala sala) {
        initComponents();
        System.out.println("hola ");
        this.setTitle("Sessiones");
        
        int x = 0;
        int w = 50;
        int y = 10;
        Sessions sc = this;
        this.setExtendedState(this.getExtendedState() | JFrame.MAXIMIZED_BOTH);
        for (var i : sala.getSessiones()){
           
            JButton butoncine = new JButton(i.getPelicula().getTitulo());
            this.add(butoncine);
            butoncine.setVisible(true);
            butoncine.setBounds(x, y, w*2, w);
            x += w*3;
            y += 20;
            
            butoncine.addActionListener(new ActionListener(){
                @Override
                public void actionPerformed(ActionEvent e) {
                    sc.dispose();
                    Butacas se = new Butacas(i,sala);
                    se.setVisible(true); 
                }
            });
            
            
        }
    }
